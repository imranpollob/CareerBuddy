import { expect, test } from '@playwright/test'

test('assessment, learning, matching and employer discovery',async ({page},testInfo)=>{
  const errors:string[]=[]
  page.on('pageerror',error=>errors.push(error.message))
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'Your next chapter starts here.'})).toBeVisible()
  await expect(page.getByText('Mock mode',{exact:true})).toBeVisible()
  await page.screenshot({path:`../.local/dashboard-${testInfo.project.name}.png`,fullPage:true})
  await page.getByRole('button',{name:'Prepare a Python assessment',exact:true}).click()
  let dialog=page.getByRole('dialog')
  await expect(dialog).toBeVisible()
  for(const [i,choice] of [1,1,0,0].entries())await dialog.locator('fieldset').nth(i).getByRole('radio').nth(choice).check()
  await dialog.getByRole('button',{name:'Submit assessment'}).click()
  await expect(dialog.getByText('0%',{exact:true})).toBeVisible()
  await dialog.getByRole('button',{name:'Back to my dashboard'}).click()
  const milestone=page.locator('.milestone').filter({hasText:'Reliable Python foundations'})
  await milestone.getByRole('button',{name:'Open lesson'}).click()
  await page.getByRole('button',{name:'I’ve practiced · Start reassessment'}).click()
  dialog=page.getByRole('dialog')
  await expect(dialog.getByRole('heading',{name:'Python · Fundamentals check'})).toBeVisible()
  for(const [i,choice] of [0,2,1,3].entries())await dialog.locator('fieldset').nth(i).getByRole('radio').nth(choice).check()
  await dialog.getByRole('button',{name:'Submit assessment'}).click()
  await expect(dialog.getByText('100%',{exact:true})).toBeVisible()
  await dialog.getByRole('button',{name:'Back to my dashboard'}).click()
  await page.getByRole('button',{name:'Job marketplace'}).click()
  const job=page.locator('.job-card').filter({hasText:'Python Engineer · AI Products'})
  await expect(job.getByText('1 of 2',{exact:true})).toBeVisible()
  await page.screenshot({path:`../.local/marketplace-${testInfo.project.name}.png`})
  await page.getByRole('button',{name:'My dashboard'}).click()
  await page.getByRole('button',{name:'Edit profile'}).click()
  await page.getByRole('checkbox',{name:'Let demo employers discover my profile'}).check()
  await page.getByRole('button',{name:'Save profile',exact:true}).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByLabel('Demo identity',{exact:true}).selectOption('employer')
  await expect(page.getByRole('heading',{name:'Meet the skills behind the profile.'})).toBeVisible()
  await page.getByLabel('Choose a job',{exact:true}).selectOption('demo-python-engineer')
  const candidate=page.locator('.candidate-card').filter({hasText:'Alex Morgan'})
  await expect(candidate).toBeVisible()
  await candidate.locator('summary').click()
  await expect(candidate.getByText('Python · 100%',{exact:true})).toBeVisible()
  await page.screenshot({path:`../.local/employer-${testInfo.project.name}.png`,fullPage:true})
  await page.getByRole('button',{name:'Create a job'}).click()
  await page.getByLabel('Job title',{exact:true}).fill('Python AI Demo Builder')
  await page.getByRole('button',{name:'Save posting'}).click()
  await expect(page.getByLabel('Choose a job',{exact:true})).toContainText('Python AI Demo Builder')
  expect(errors).toEqual([])
  const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth)
  expect(overflow).toBe(false)
})

test('student reaches early-career jobs and shares only consenting evidence',async ({page},testInfo)=>{
  await page.goto('/')
  await page.getByRole('heading',{name:'Your next chapter starts here.'}).waitFor()
  await page.getByLabel('Demo identity',{exact:true}).selectOption('student')
  await expect(page.getByText('Student → First AI Engineering Role',{exact:true})).toBeVisible()
  await expect(page.getByText('Internship / entry sample',{exact:true})).toBeVisible()
  await page.screenshot({path:`../.local/student-${testInfo.project.name}.png`,fullPage:true})
  await page.getByRole('button',{name:'Prepare a Python assessment',exact:true}).click()
  const dialog=page.getByRole('dialog')
  for(const [i,choice] of [0,2,1,3].entries())await dialog.locator('fieldset').nth(i).getByRole('radio').nth(choice).check()
  await dialog.getByRole('button',{name:'Submit assessment'}).click()
  await expect(dialog.getByText('100%',{exact:true})).toBeVisible()
  await dialog.getByRole('button',{name:'Back to my dashboard'}).click()
  await page.getByRole('button',{name:'Job marketplace'}).click()
  await expect(page.getByLabel('Career stage',{exact:true})).toHaveValue('early')
  const internship=page.locator('.job-card').filter({hasText:'AI Engineering Intern'})
  await expect(internship.getByText('1 of 3',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'My dashboard'}).click()
  await page.getByRole('button',{name:'Edit profile'}).click()
  await page.getByRole('checkbox',{name:'Let demo employers discover my profile'}).check()
  await page.getByRole('button',{name:'Save profile',exact:true}).click()
  await expect(page.getByRole('dialog')).not.toBeVisible()
  await page.getByLabel('Demo identity',{exact:true}).selectOption('employer')
  await page.getByLabel('Choose a job',{exact:true}).selectOption('demo-junior-ai')
  const student=page.locator('.candidate-card').filter({hasText:'Priya Shah'})
  await expect(student).toBeVisible()
  await expect(student.getByText('Student / graduate',{exact:true})).toBeVisible()
  await student.locator('summary').click()
  await expect(student.getByText('Graded during this demo',{exact:true})).toBeVisible()
  await expect(page.getByText('Taylor Reed',{exact:true})).not.toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth)).toBe(false)
})
