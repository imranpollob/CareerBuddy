import { expect, test, type Page } from '@playwright/test'
import { readFileSync } from 'node:fs'

function credentials(actor:string){return JSON.parse(readFileSync(new URL('../../.local/test-actor-accounts.json',import.meta.url),'utf8'))[actor]}
async function login(page:Page,actor:string){
  const account=credentials(actor)
  await page.getByLabel('Email address',{exact:true}).fill(account.email)
  await page.getByLabel('Password',{exact:true}).fill(account.password)
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  await expect(page.getByRole('button',{name:'Ask SkillPilot',exact:true})).toBeVisible()
}
async function logout(page:Page){await page.getByRole('button',{name:'Sign out',exact:true}).filter({visible:true}).click();await expect(page.getByRole('heading',{name:'Sign in to SkillPilot'})).toBeVisible()}
async function gradePython(page:Page,choices:number[]){
  const dialog=page.getByRole('dialog',{name:'Python · Fundamentals check'})
  await expect(dialog).toBeVisible()
  for(const [i,choice] of choices.entries())await dialog.locator('fieldset').nth(i).getByRole('radio').nth(choice).check()
  await dialog.getByRole('button',{name:'Submit assessment'}).click()
  await expect(dialog.getByRole('button',{name:'Back to my dashboard'})).toBeVisible()
}

test('signed-in engineer learns, reassesses, and appears to employer with consent',async({page},testInfo)=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/')
  await expect(page.getByRole('heading',{name:'Sign in to SkillPilot'})).toBeVisible()
  await page.screenshot({path:`../.local/signin-${testInfo.project.name}.png`,fullPage:true})
  await login(page,'candidate')
  await expect(page.getByRole('heading',{name:'Good to see you, Alex.'})).toBeVisible()
  await expect(page.getByLabel('Demo identity',{exact:true})).toHaveCount(0)
  await expect(page.getByRole('dialog',{name:'SkillPilot career assistant'})).not.toBeVisible()
  await page.screenshot({path:`../.local/product-overview-${testInfo.project.name}.png`,fullPage:true})
  await page.getByRole('button',{name:'Ask SkillPilot',exact:true}).click()
  await page.getByRole('button',{name:'Prepare a Python assessment',exact:true}).click()
  await gradePython(page,[1,1,0,0])
  await expect(page.getByRole('dialog').getByText('0%',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Back to my dashboard'}).click()
  await page.getByRole('button',{name:'Learning plan',exact:true}).click()
  await page.locator('.milestone').filter({hasText:'Reliable Python foundations'}).getByRole('button',{name:'Open lesson'}).click()
  await page.getByRole('button',{name:'I’ve practiced · Start reassessment'}).click()
  await gradePython(page,[0,2,1,3])
  await expect(page.getByRole('dialog').getByText('100%',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Back to my dashboard'}).click()
  await page.getByRole('button',{name:'Find jobs',exact:true}).click()
  await expect(page.locator('.job-card').filter({hasText:'Python Engineer · AI Products'}).getByText('1 of 2',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Overview',exact:true}).click()
  await page.getByRole('button',{name:'Edit profile'}).click()
  await page.getByRole('checkbox',{name:'Make my profile discoverable to employers'}).check()
  await page.getByRole('button',{name:'Save profile',exact:true}).click()
  await expect(page.getByRole('dialog',{name:'My profile'})).not.toBeVisible()
  await logout(page);await login(page,'employer')
  await page.getByLabel('Choose a job',{exact:true}).selectOption('demo-python-engineer')
  const alex=page.locator('.candidate-card').filter({hasText:'Alex Morgan'})
  await expect(alex).toBeVisible();await alex.locator('summary').click()
  await expect(alex.getByText('Python · 100%',{exact:true})).toBeVisible()
  await page.screenshot({path:`../.local/product-employer-${testInfo.project.name}.png`,fullPage:true})
  await page.getByRole('button',{name:'Create a job'}).click()
  await page.getByLabel('Job title',{exact:true}).fill('Python AI Builder')
  await page.getByLabel('Company',{exact:true}).fill('Northstar Labs')
  await page.getByLabel('Description',{exact:true}).fill('Build useful AI applications with Python and retrieval.')
  await page.getByRole('button',{name:'Save posting'}).click()
  await expect(page.getByLabel('Choose a job',{exact:true})).toContainText('Python AI Builder')
  expect(errors).toEqual([])
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false)
})

test('new user signs up, retains their account, and gets a private student workspace',async({page},testInfo)=>{
  await page.goto('/')
  await page.getByRole('button',{name:'Create an account',exact:true}).click()
  const email=`new-${testInfo.project.name}-${Date.now()}@example.com`
  const password='Browser test account 2026!'
  await page.getByLabel('Full name',{exact:true}).fill('Jamie Patel')
  await page.getByLabel('Email address',{exact:true}).fill(email)
  await page.getByLabel('Password',{exact:true}).fill(password)
  await page.getByRole('button',{name:'Continue',exact:true}).click()
  await page.getByLabel('Career background',{exact:true}).selectOption('student')
  await page.getByLabel('Current role or field of study',{exact:true}).fill('Computer Science Student')
  await page.getByRole('checkbox',{name:'Python',exact:true}).check()
  await page.getByRole('button',{name:'Create account',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Good to see you, Jamie.'})).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading',{name:'Good to see you, Jamie.'})).toBeVisible()
  await page.getByRole('button',{name:'Find jobs',exact:true}).click()
  await expect(page.getByLabel('Career stage',{exact:true})).toHaveValue('early')
  await page.getByRole('button',{name:'Overview',exact:true}).click()
  await page.getByRole('button',{name:'Edit profile'}).click()
  await expect(page.getByRole('checkbox',{name:'Make my profile discoverable to employers'})).not.toBeChecked()
  await page.getByRole('button',{name:'Close dialog'}).click()
  await page.getByRole('button',{name:'Switch to dark theme'}).click()
  await page.screenshot({path:`../.local/product-dark-${testInfo.project.name}.png`,fullPage:true})
  await logout(page)
  await page.getByLabel('Email address',{exact:true}).fill(email)
  await page.getByLabel('Password',{exact:true}).fill(password)
  await page.getByRole('button',{name:'Sign in',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Good to see you, Jamie.'})).toBeVisible()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false)
})
