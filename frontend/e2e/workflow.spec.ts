test('chat renders rich Markdown safely and shows a pending-generation loader',async({page},testInfo)=>{
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.addInitScript(()=>{Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async(text:string)=>{(window as Window&{copiedCode?:string}).copiedCode=text}}})})
 await page.route('**/api/chat/history',route=>route.fulfill({json:{revision:0,messages:[]}}))
 const markdown='# A path to AI engineering\n\n**Start small**, then build confidence with `Python`.\n\n1. Learn the fundamentals.\n2. Build one useful project.\n\n```python\nprint("hello, career")\n```\n\n| Skill | Next step |\n| --- | --- |\n| Python | Practice |\n\n[Python documentation](https://docs.python.org/3/)\n\n[Unsafe link](javascript:alert(1))\n\n<script>window.unsafeMarkdownExecuted = true</script>\n\n![tracking image](https://invalid.example/pixel.png)'
 await page.route('**/api/chat',async route=>{await new Promise(resolve=>setTimeout(resolve,1800));await route.fulfill({json:{message:markdown,mode:'mock',delegations:[]}})})
 await page.goto('/');await login(page,'candidate');await nav(page,'AI Chat')
 await page.getByRole('textbox',{name:'Message CareerBuddy'}).fill('Show me a useful career plan')
 await page.getByRole('button',{name:'Send message',exact:true}).click()
 const loader=page.locator('.generation-loader').filter({hasText:'Connecting the dots'})
 await expect(loader).toBeVisible()
 expect(await loader.locator('.buddy-face').evaluate(el=>getComputedStyle(el).animationName)).toBe('none')
 await page.screenshot({path:`../.local/modern-thinking-${testInfo.project.name}.png`,fullPage:true})
 await expect(page.getByRole('heading',{name:'A path to AI engineering',exact:true})).toBeVisible()
 await expect(page.locator('.generation-loader')).toHaveCount(0)
 await expect(page.locator('.markdown-content strong').getByText('Start small',{exact:true})).toBeVisible()
 await expect(page.locator('.markdown-content ol>li')).toHaveCount(2)
 await expect(page.getByRole('table')).toBeVisible()
 await expect(page.locator('.markdown-content pre')).toContainText('print("hello, career")')
 const link=page.getByRole('link',{name:'Python documentation',exact:true})
 await expect(link).toHaveAttribute('rel','noopener noreferrer')
 await expect(page.locator('.markdown-content a[href^="javascript:"]')).toHaveCount(0)
 await expect(page.locator('.markdown-content script,.markdown-content img')).toHaveCount(0)
 expect(await page.evaluate(()=>Boolean((window as Window&{unsafeMarkdownExecuted?:boolean}).unsafeMarkdownExecuted))).toBe(false)
 await page.getByRole('button',{name:'Copy code',exact:true}).click()
 await expect(page.getByRole('button',{name:'Code copied',exact:true})).toBeVisible()
 expect(await page.evaluate(()=>(window as Window&{copiedCode?:string}).copiedCode)).toContain('print("hello, career")')
 await page.screenshot({path:`../.local/modern-markdown-${testInfo.project.name}.png`,fullPage:true})
 await page.unroute('**/api/chat')
 await page.route('**/api/chat',async route=>{await new Promise(resolve=>setTimeout(resolve,1000));await route.fulfill({status:503,json:{detail:'The AI service is temporarily unavailable. Please retry.'}})})
 await page.getByRole('textbox',{name:'Message CareerBuddy'}).fill('Retry my career question')
 await page.getByRole('button',{name:'Send message',exact:true}).click()
 await expect(page.locator('.generation-loader')).toBeVisible()
 await expect(page.getByRole('alert')).toContainText('temporarily unavailable')
 await expect(page.locator('.generation-loader')).toHaveCount(0)
 await expect(page.getByRole('textbox',{name:'Message CareerBuddy'})).toHaveValue('Retry my career question')
 await expect(page.getByRole('button',{name:'Send message',exact:true})).toBeEnabled()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false)
})
